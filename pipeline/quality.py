"""
Data-quality bookkeeping shared by the cleaning stage.

* IdSet / IdValues -- memory-light key lookups that work across chunks.
  Keys are dense positive integers, so instead of a Python set (~70 bytes
  per key) we keep a NumPy array indexed by the key itself: 1 byte per key
  for membership, 4-8 bytes for a stored value. 11.6M session ids -> ~12 MB.
* DQReport -- counts rows in / out, rejections and repairs per rule, writes
  rejected rows to data/rejected/<table>_rejected.csv with a reject_reason,
  and renders the Markdown + JSON data-quality report.
"""

from __future__ import annotations

import ctypes
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd


def release_memory() -> None:
    """Ask glibc to hand freed heap pages back to the OS between chunks.
    Without it, resident memory reflects the largest chunk ever seen plus
    fragmentation, not what the pipeline is actually holding. No-op off Linux."""
    if sys.platform.startswith("linux"):
        try:
            ctypes.CDLL("libc.so.6").malloc_trim(0)
        except OSError:
            pass


class IdSet:
    def __init__(self, capacity: int = 1 << 16):
        self._bits = np.zeros(capacity, dtype=bool)

    def _ensure(self, max_id: int) -> None:
        if max_id >= self._bits.size:
            new = np.zeros(max(max_id + 1, self._bits.size * 2), dtype=bool)
            new[: self._bits.size] = self._bits
            self._bits = new

    def add(self, ids) -> None:
        ids = np.asarray(ids, dtype=np.int64)
        if ids.size:
            self._ensure(int(ids.max()))
            self._bits[ids] = True

    def contains(self, ids) -> np.ndarray:
        ids = np.asarray(ids, dtype=np.int64)
        out = np.zeros(ids.size, dtype=bool)
        ok = (ids >= 0) & (ids < self._bits.size)
        out[ok] = self._bits[ids[ok]]
        return out

    def __len__(self) -> int:
        return int(self._bits.sum())


class IdValues:
    """Stores one numeric value per integer key (e.g. order_id -> order day)."""

    def __init__(self, dtype=np.int32, missing=-1, capacity: int = 1 << 16):
        self._dtype, self._missing = dtype, missing
        self._vals = np.full(capacity, missing, dtype=dtype)

    def set(self, ids, values) -> None:
        ids = np.asarray(ids, dtype=np.int64)
        if not ids.size:
            return
        if ids.max() >= self._vals.size:
            new = np.full(max(int(ids.max()) + 1, self._vals.size * 2), self._missing, self._dtype)
            new[: self._vals.size] = self._vals
            self._vals = new
        self._vals[ids] = values

    def get(self, ids) -> np.ndarray:
        ids = np.asarray(ids, dtype=np.int64)
        out = np.full(ids.size, self._missing, dtype=self._dtype)
        ok = (ids >= 0) & (ids < self._vals.size)
        out[ok] = self._vals[ids[ok]]
        return out


class DQReport:
    def __init__(self, rejected_dir: Path):
        self.rejected_dir = rejected_dir
        self.rows_in: dict[str, int] = defaultdict(int)
        self.rows_out: dict[str, int] = defaultdict(int)
        self.rejected: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
        self.repaired: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
        self._started: set[str] = set()

    def reject(self, table: str, rule: str, rows: pd.DataFrame) -> None:
        if rows.empty:
            return
        self.rejected[table][rule] += len(rows)
        path = self.rejected_dir / f"{table}_rejected.csv"
        first = table not in self._started
        rows.assign(reject_reason=rule).to_csv(path, mode="w" if first else "a",
                                               header=first, index=False)
        self._started.add(table)

    def repair(self, table: str, rule: str, n: int) -> None:
        if n:
            self.repaired[table][rule] += int(n)

    def to_dict(self) -> dict:
        return {t: {"rows_in": self.rows_in[t], "rows_out": self.rows_out[t],
                    "rows_rejected": sum(self.rejected[t].values()),
                    "rejected_by_rule": dict(self.rejected[t]),
                    "repaired_by_rule": dict(self.repaired[t])}
                for t in self.rows_in}

    def write(self, reports_dir: Path, manifest_path: Path | None = None) -> Path:
        reports_dir.mkdir(parents=True, exist_ok=True)
        data = self.to_dict()
        (reports_dir / "data_quality_report.json").write_text(json.dumps(data, indent=2))

        lines = ["# Data-quality report", "",
                 "Generated by `python -m pipeline run --stage clean`. A row is attributed to the "
                 "**first** rule it fails (rules run in the order listed). Rejected rows, with "
                 "their reason, are in `data/rejected/<table>_rejected.csv`.", "",
                 "## Summary", "",
                 "| Table | Rows in | Rows rejected | Rows out | Rejected % |",
                 "|---|---:|---:|---:|---:|"]
        for t, d in data.items():
            pct = 100 * d["rows_rejected"] / d["rows_in"] if d["rows_in"] else 0
            lines.append(f"| {t} | {d['rows_in']:,} | {d['rows_rejected']:,} | "
                         f"{d['rows_out']:,} | {pct:.2f}% |")
        lines += ["", "## Rejected rows per rule", "", "| Table | Rule | Rows |", "|---|---|---:|"]
        for t, d in data.items():
            for rule, n in d["rejected_by_rule"].items():
                lines.append(f"| {t} | `{rule}` | {n:,} |")
        lines += ["", "## Repaired (kept) rows per rule", "",
                  "Problems that are fixable without losing the row are repaired and counted.", "",
                  "| Table | Rule | Rows |", "|---|---|---:|"]
        for t, d in data.items():
            for rule, n in d["repaired_by_rule"].items():
                lines.append(f"| {t} | `{rule}` | {n:,} |")

        if manifest_path and manifest_path.exists():
            injected = json.loads(manifest_path.read_text()).get("injected_issues", {})
            lines += ["", "## Injected vs detected (synthetic data only)", "",
                      "The generator records how many dirty rows it injected; this compares them "
                      "with what the rules caught. Totals can differ legitimately: one row can carry "
                      "two injected issues, and rejecting a parent also rejects its children "
                      "(`parent_*_rejected`).", "",
                      "| Table | Injected issue | Injected |", "|---|---|---:|"]
            for t, issues in injected.items():
                for issue, n in issues.items():
                    lines.append(f"| {t} | {issue} | {n:,} |")
        path = reports_dir / "data_quality_report.md"
        path.write_text("\n".join(lines) + "\n")
        return path
